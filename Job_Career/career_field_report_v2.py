def _macro_cluster_ranking(results: List[Dict], top_n: int = 20) -> List[Dict]:
    """Build macro-cluster ranking using actual field scores and rank decay.

    Fixes:
    - No artificial 100/85/70/55 strength labels.
    - Uses actual final_score evidence.
    - Keeps report_utils grouping/floor/cap logic.
    - Preserves deterministic result order.
    """
    groups = _top20_as_four_cluster_groups((results or [])[:top_n])
    if not groups:
        return []

    raw_groups = []

    for cluster, rows in groups:
        raw_strength = 0.0
        member_rows = []

        for rank, row in rows:
            try:
                score = float(row.get("final_score", 0.0) or 0.0)
            except Exception:
                score = 0.0

            # Earlier ranks matter more, but lower-ranked sibling fields still contribute.
            rank_decay = 1.0 / (float(rank) ** 0.65)
            raw_strength += score * rank_decay
            member_rows.append(row)

        raw_groups.append({
            "cluster": cluster,
            "rows": rows,
            "member_rows": member_rows,
            "raw_strength": raw_strength,
        })

    max_strength = max((g["raw_strength"] for g in raw_groups), default=1.0) or 1.0

    raw_groups.sort(key=lambda g: g["raw_strength"], reverse=True)

    out = []
    for i, g in enumerate(raw_groups, 1):
        rows = g["rows"]
        member_rows = g["member_rows"]
        strength_pct = round(100.0 * g["raw_strength"] / max_strength, 1)

        out.append({
            "rank": i,
            "cluster": g["cluster"],
            "strength_pct": strength_pct,
            "raw_strength": round(g["raw_strength"], 3),
            "member_fields": [_field_display_name(r) for r in member_rows],
            "best_rank_in_cluster": min(rank for rank, _ in rows) if rows else None,
        })

    return out

def apply_cluster_coherence_guard(results: List[Dict]) -> List[Dict]:
    """Apply a bounded post-score coherence guard.

    Purpose:
    - Protect the lower top-20 from weak cross-cluster residue.
    - Keep strong adjacent physical/materials/engineering fields visible.
    - Do not touch the top identity aggressively.
    - Record every adjustment for audit.

    This is deterministic and bounded. It should be applied after run_engine()
    and v12 enrichment, before macro cluster calculation.
    """
    if not results:
        return results

    top7 = results[:7]

    top7_families = {
        r.get("career_family")
        for r in top7
        if r.get("career_family")
    }

    top7_competencies = {
        r.get("competency")
        for r in top7
        if r.get("competency")
    }

    physical_anchor_families = {
        "materials_extractive",
        "mechanical_manufacturing",
        "aerospace_aeronautics",
        "space_systems_propulsion",
        "physical_chemical_sciences",
        "process_chemical",
        "systems_electronics",
    }

    physical_anchor_competencies = {
        "physical_mechanical",
        "frontier_space",
        "systems_electronics",
        "life_earth_sciences",
    }

    dominant_physical_profile = bool(
        top7_families & physical_anchor_families
        or top7_competencies & physical_anchor_competencies
    )

    if not dominant_physical_profile:
        return results

    weak_cross_cluster_field_ids = {
        "gender_studies",
        "fisheries_science",
        "public_health",
        "rural_management",
        "mass_communication",
        "journalism_media",
        "visual_communication",
        "hospitality_management",
    }

    protected_adjacent_families = {
        "materials_extractive",
        "mechanical_manufacturing",
        "aerospace_aeronautics",
        "space_systems_propulsion",
        "physical_chemical_sciences",
        "process_chemical",
        "systems_electronics",
        "data_quant_analytics",
        "applied_computational",
    }

    out: List[Dict] = []

    for idx, row in enumerate(results):
        r = dict(row)
        fid = str(
            r.get("field_id")
            or r.get("branch_id")
            or r.get("id")
            or r.get("key")
            or ""
        )
        fam = str(r.get("career_family") or "")
        score = float(r.get("final_score", 0.0) or 0.0)

        # Never disturb the top 10 aggressively. The guard is for lower top-20 leakage.
        if idx >= 10 and fid in weak_cross_cluster_field_ids and fam not in protected_adjacent_families:
            r["final_score"] = round(score * 0.88, 3)
            r.setdefault("post_v12_adjustments", []).append(
                "cluster_coherence_guard: weak cross-cluster residue demoted under dominant physical/materials profile"
            )

        # Small preservation boost for adjacent technical families below the top 10.
        elif idx >= 10 and fam in protected_adjacent_families and score >= 30:
            r["final_score"] = round(score * 1.025, 3)
            r.setdefault("post_v12_adjustments", []).append(
                "cluster_coherence_guard: adjacent physical/technical field preserved"
            )

        out.append(r)

    return sorted(out, key=lambda x: float(x.get("final_score", 0.0) or 0.0), reverse=True)

def _build_chart_signature_facts(payload: NatalPayloadV2, active_lord: str, peak_lord: str) -> Dict[str, Any]:
    """Pull the raw chart facts (no interpretation) that the LLM will explain."""
    house_lords = getattr(payload, "house_lords", {}) or {}
    dob = getattr(payload, "dob", "") or ""
    ug_start_year = ""
    try:
        # Indian UG admission normally follows the Class 12 year. Students born
        # after the Sep admission cutoff usually join in the next calendar year.
        birth_dt = datetime.strptime(str(dob), "%Y-%m-%d")
        ug_start_year = birth_dt.year + (19 if birth_dt.month >= 10 else 18)
    except Exception:
        current_age = float(getattr(payload, "current_age", 0) or 0)
        if current_age:
            ug_start_year = datetime.now().year + max(0, int(round(18 - current_age)))
    return {
        "lagna_sign": getattr(payload, "lagna_sign", "") or getattr(payload, "ascendant_sign", ""),
        "h10_lord": house_lords.get(10, house_lords.get("10", "")),
        "active_mahadasha_lord": active_lord,
        "peak_career_mahadasha_lord": peak_lord,
        "dob": dob,
        "current_age": getattr(payload, "current_age", 0),
        "ug_start_year": ug_start_year,
        "eff_strengths_top3": sorted(
            (getattr(payload, "eff_strengths", {}) or {}).items(), key=lambda x: -x[1]
        )[:3],
        "arudha_lagna": getattr(payload, "arudha_lagna", ""),
        "arudha_pada_h10": getattr(payload, "arudha_pada_h10", ""),
        "academic_tier_recommendation": getattr(payload, "academic_tier_recommendation", {}) or {},
        "edu_stream": getattr(payload, "edu_stream", {}) or {},
    }


