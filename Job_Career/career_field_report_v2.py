def _apply_deterministic_suitability_to_report(report: Dict[str, Any], rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Prevent either fallback prose or an LLM from reverting to the old
    parent-safe binary rule. Rankings remain unchanged; only route-status
    labels and their auditable reasons are synchronized.
    """
    by_label = {_field_display_name(r): r.get("recommendation_assessment", {}) for r in rows[:20]}
    for item in report.get("top_20_fields", []) or []:
        if not isinstance(item, dict):
            continue
        assessment = by_label.get(str(item.get("field", "")))
        if assessment:
            item["recommended_level"] = assessment.get("recommendation_status", item.get("recommended_level", ""))

    # Route-suitability statuses are NOT interchangeable with "avoid as
    # primary". STATUS_NOT_PRIMARY is the only status backed by independent,
    # multi-dimensional adverse evidence (see field_suitability.py) and is
    # the only one that belongs in the true "avoid" list. STATUS_PG,
    # STATUS_EXPLORATORY and STATUS_REQUIRES_VALIDATION describe fields that
    # are still viable (as a PG route, a secondary option, or pending more
    # data) and are reported in their own buckets so a PG-dependent field is
    # never displayed as if it were rejected.
    caution_statuses = {STATUS_PG, STATUS_EXPLORATORY, STATUS_NOT_PRIMARY, STATUS_REQUIRES_VALIDATION}

    def bucket_for(status: str, row: Dict[str, Any], assessment: Dict[str, Any]) -> Dict[str, Any]:
        reason_parts = (
            (assessment.get("contraindications") or [])
            + (assessment.get("conditions") or [])
            + (assessment.get("missing_validations") or [])[:1]
        )
        return {
            "field": _field_display_name(row),
            "status": status,
            "reason": "; ".join(reason_parts) or "See route-suitability assessment for detail.",
            "assessment": assessment,
        }

    route_cautions, true_avoid, pg_specialization, exploratory, requires_validation = [], [], [], [], []
    for row in rows[:20]:
        assessment = row.get("recommendation_assessment", {})
        status = assessment.get("recommendation_status", "")
        if status not in caution_statuses:
            continue
        entry = bucket_for(status, row, assessment)
        route_cautions.append(entry)
        if status == STATUS_NOT_PRIMARY:
            true_avoid.append(entry)
        elif status == STATUS_PG:
            pg_specialization.append(entry)
        elif status == STATUS_EXPLORATORY:
            exploratory.append(entry)
        elif status == STATUS_REQUIRES_VALIDATION:
            requires_validation.append(entry)

    # "Route Suitability Cautions" (section 7 table) intentionally shows all
    # four caution statuses side by side, with the status column making the
    # distinction explicit. "fields_to_avoid" — which drives the rail pills
    # and the "Avoid As Primary" verdict — is restricted to true rejects.
    report["route_cautions"] = route_cautions
    report["fields_to_avoid"] = true_avoid
    report["pg_specialization_fields"] = pg_specialization
    report["exploratory_fields"] = exploratory
    report["requires_validation_fields"] = requires_validation

    snapshot = report.setdefault("snapshot", {})
    if true_avoid:
        avoid_names = ", ".join(a["field"] for a in true_avoid)
        snapshot["avoid_as_primary"] = (
            f"{avoid_names} — not recommended as a primary route (independent adverse evidence in "
            f"two or more suitability dimensions). PG-dependent and exploratory fields are listed "
            f"separately and are not avoided."
        )
    else:
        snapshot["avoid_as_primary"] = (
            "No field in the top 20 shows multi-dimensional adverse evidence; "
            "PG-dependent and exploratory routes are listed separately below."
        )

    # Recompute the PG route deterministically from the actual PG-dependence
    # flag, overriding whatever rank-based guess the LLM or fallback made —
    # this is the same fix applied to the deterministic fallback path, kept
    # authoritative here so it also corrects LLM-authored reports.
    primary_row = rows[0] if rows else {}
    pg_row = _select_pg_route_row(rows, primary_row=primary_row)
    if pg_row:
        snapshot["best_pg_route"] = _field_display_name(pg_row) or snapshot.get("best_pg_route", "")

    report["disclaimer"] = UNIVERSAL_DISCLAIMER
    report["validation_status"] = evidence_status(inputs_complete=True, computed=True)
    return report


