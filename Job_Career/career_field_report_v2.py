def _validate_professional_tone(data: Dict[str, Any]) -> None:
    """Validate parent/student report tone.

    Parent and student summaries should be advisory, calm, and non-fatalistic.
    Astrological terms are acceptable in the astrological_signature section,
    but not in the parent/student summary blocks.
    """
    parent = str(data.get("parent_summary", "") or "").lower()
    student = str(data.get("student_summary", "") or "").lower()
    final = str(data.get("final_recommendation", "") or "").lower()

    parent_jargon = [term for term in _PARENT_ASTROLOGY_JARGON if term in parent]
    if parent_jargon:
        raise ValueError(f"Parent summary contains astrology jargon: {parent_jargon}")

    overclaims = [
        term for term in _FORBIDDEN_OVERCLAIMS
        if term in parent or term in student or term in final
    ]
    if overclaims:
        raise ValueError(f"Report contains fatalistic/overclaiming language: {overclaims}")


def _validate_report_json(
    data: Dict[str, Any],
    allowed_fields: Optional[set] = None,
    allowed_clusters: Optional[set] = None,
) -> None:
    """Strict validation for the structured LLM report.

    Checks:
    - Required top-level schema keys.
    - LLM did not invent field names.
    - LLM did not invent macro-cluster names.
    - LLM did not return more than top 20 fields.
    - Parent/student prose stays professional.
    """
    if not isinstance(data, dict):
        raise ValueError("LLM report must be a JSON object")

    missing = [k for k in _REQUIRED_REPORT_KEYS if k not in data]
    if missing:
        raise ValueError(f"Missing required keys: {missing}")

    allowed_fields = allowed_fields or set()
    allowed_clusters = allowed_clusters or set()

    top_fields = data.get("top_20_fields", [])
    if not isinstance(top_fields, list):
        raise ValueError("top_20_fields must be a list")

    if len(top_fields) > 20:
        raise ValueError(f"LLM returned more than 20 fields: {len(top_fields)}")

    if allowed_fields:
        for item in top_fields:
            if not isinstance(item, dict):
                raise ValueError("Each top_20_fields item must be an object")
            field = str(item.get("field", "") or "").strip()
            if field and field not in allowed_fields:
                raise ValueError(f"LLM invented or renamed top field: {field}")

        for item in data.get("fields_to_avoid", []) or []:
            if not isinstance(item, dict):
                continue
            field = str(item.get("field", "") or "").strip()
            if field and field not in allowed_fields:
                raise ValueError(f"LLM invented avoid-list field: {field}")

        for item in data.get("engine_output_comparison", []) or []:
            if not isinstance(item, dict):
                continue
            field = str(item.get("engine_field", "") or "").strip()
            if field and field not in allowed_fields:
                raise ValueError(f"LLM invented comparison field: {field}")

    if allowed_clusters:
        for item in data.get("macro_cluster_interpretations", []) or []:
            if not isinstance(item, dict):
                continue
            cluster = str(item.get("cluster", "") or "").strip()
            if cluster and cluster not in allowed_clusters:
                raise ValueError(f"LLM invented macro cluster: {cluster}")

    _validate_professional_tone(data)


def _call_llm_for_report(
    student_name: str,
    career_phase: str,
    active_lord: str,
    peak_lord: str,
    chart_facts: Dict[str, Any],
    top35: List[Dict],
    macro_clusters: List[Dict],
    locked: Optional[Dict[str, Any]] = None,
) -> Optional[Dict]:
    """Single structured LLM call producing every narrative/judgement field.

    Fixes:
    - Uses strict field/cluster validation.
    - Validates parent/student tone.
    - Logs provider/model/key availability.
    - Avoids treating LLM output as scoring authority.
    """
    try:
        from jyotish.engine_io import _maybe_load_dotenv as _dotenv_fn
        _dotenv_fn()
    except Exception:
        pass

    provider_name = os.getenv("LLM_PROVIDER", "gemini").lower()
    env_var, default_model, call_fn = _LLM_PROVIDERS.get(
        provider_name,
        _LLM_PROVIDERS["gemini"],
    )
    model_override = os.getenv("LLM_MODEL", default_model)
    api_key = os.getenv(env_var)

    logger.info(
        "[career_field_report_v2] LLM provider=%s model=%s key_present=%s",
        provider_name,
        model_override,
        bool(api_key),
    )
    preflight = llm_provider_preflight(provider_name)
    if not preflight["ready"]:
        logger.error(
            "[career_field_report_v2] LLM provider preflight failed: %s. Install with `%s`.",
            preflight, preflight.get("install_extra", ""),
        )
        return None

    if not api_key:
        logger.warning(
            "%s missing (provider=%s) — report will use deterministic fallback text.",
            env_var,
            provider_name,
        )
        return None

    allowed_fields = {
        _field_display_name(r)
        for r in (top35 or [])[:35]
        if _field_display_name(r)
    }

    allowed_clusters = {
        str(c.get("cluster", "") or "").strip()
        for c in (macro_clusters or [])
        if isinstance(c, dict) and str(c.get("cluster", "") or "").strip()
    }

    def _strict_validator(data: Dict[str, Any]) -> None:
        _validate_report_json(
            data,
            allowed_fields=allowed_fields,
            allowed_clusters=allowed_clusters,
        )

    client = _ProviderClientWrapper(call_fn, api_key, model_override)
    user_prompt = _build_report_user_prompt(
        student_name,
        career_phase,
        active_lord,
        peak_lord,
        chart_facts,
        top35,
        macro_clusters,
        locked=locked,
    )

    messages = [
        {"role": "system", "content": _REPORT_SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]

    schema = {"schema": {"required": [], "properties": {}}}

    try:
        return _run_llm_with_retry(
            client,
            messages,
            schema,
            _strict_validator,
            max_retries=3,
        )
    except Exception as exc:
        msg = str(exc)
        if "billing_not_active" in msg or "account is not active" in msg:
            logger.error(
                "[career_field_report_v2] LLM billing inactive for provider=%s. "
                "Enable API billing or use a key from an active billed project.",
                provider_name,
            )
            return None

        logger.error("[career_field_report_v2] Unexpected LLM report failure: %s", exc)
        return None


