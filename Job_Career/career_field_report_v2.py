def build_career_field_report_from_chart(
    chart: Any,
    student_name: Optional[str] = None,
    render_html: bool = False,
    precomputed_results: Optional[List[Dict[str, Any]]] = None,
    enable_llm_field_explanations: bool = False,
    output_dir: str = "educational_records",
    force_llm_report: bool = False,
) -> Dict[str, Any]:
    """API adapter: run the deterministic field pipeline and return JSON for the API.

    Mirrors :func:`generate_career_field_report_v2` but returns a dict instead of
    writing HTML. Used by ``api/education_analysis.py`` (UG endpoint).
    """
    if isinstance(chart, (str, os.PathLike)):
        with open(chart, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        chart_path = str(chart)
    else:
        data = chart
        chart_path = None

    payload = parse_json_payload(data, chart_path=chart_path)
    name = student_name or getattr(payload, "name", "Unknown")

    _env_llm_consent = str(os.getenv("LLM_REPORT_CONSENT", "")).strip().lower() in {"1", "true", "yes", "on"}
    _llm_consent = (
        force_llm_report
        or bool(getattr(payload, "external_llm_consent", False))
        or _env_llm_consent
    )
    if force_llm_report:
        logger.info("[career_field_report_v2] API mode: LLM report narrative forced on.")
    elif _env_llm_consent:
        logger.info("[career_field_report_v2] LLM consent granted via LLM_REPORT_CONSENT env var.")

    if precomputed_results is None:
        results = run_engine(payload, enable_llm=bool(enable_llm_field_explanations and _llm_consent))
    else:
        results = deepcopy(precomputed_results)
        logger.info("[career_field_report_v2] Reusing %d precomputed engine rows.", len(results))

    from Field_Determination.debug_payload_split import slim_for_render
    results = slim_for_render(results)

    try:
        from .sbc import SarvatobhadraEngine

        sbc_results = SarvatobhadraEngine(payload).apply_to_ranking([dict(r) for r in results])
        sbc_by_id: Dict[str, Dict[str, Any]] = {}
        for srow in sbc_results:
            skey = (
                srow.get("field_id") or srow.get("branch_id") or srow.get("id")
                or srow.get("key") or _field_display_name(srow)
            )
            sbc_by_id[str(skey)] = srow
        for r in results:
            rkey = (
                r.get("field_id") or r.get("branch_id") or r.get("id")
                or r.get("key") or _field_display_name(r)
            )
            s = sbc_by_id.get(str(rkey), {})
            r["sbc_manifestation"] = {
                "smi": s.get("smi"),
                "timing_band": s.get("timing_band"),
                "sbc_notes": s.get("sbc_notes", []),
                "advisory_only": True,
            }
        logger.info("SBC advisory layer applied to %d fields. Aptitude ranking preserved.", len(results))
    except Exception as sbc_err:
        logger.warning("[career_field_report_v2] SBC advisory layer unavailable: %s", sbc_err)

    registry_v12 = _load_course_registry()
    for row in results:
        fid = _row_field_id(row)
        meta = registry_v12.get(fid, {}) if fid else {}
        row["registry_v12"] = _v12_registry_slice(meta)
        for key in ("education_realism", "curriculum", "market", "risk", "routes"):
            if not row.get(key) and isinstance(meta.get(key), dict):
                row[key] = meta[key]

    student_ctx = (data.get("student_context", {}) if isinstance(data, dict) else {}) or {}
    preference = student_ctx.get("student_preference", {}) or {}
    academic_profile = (
        student_ctx.get("academic_profile")
        or preference.get("academic_profile")
        or preference.get("subject_scores")
        or {}
    )
    results = annotate_field_suitability(
        results,
        academic_profile=academic_profile,
        risk_appetite=getattr(payload, "risk_appetite", "MODERATE"),
    )

    current_age = float(getattr(payload, "current_age", 0) or 0)
    active_lord = _get_active_dasha_lord(getattr(payload, "dasha_sequence", []), current_age)
    peak_lord = getattr(payload, "peak_dasha_lord", "") or active_lord
    age_stage = classify_age_stage(current_age, results)
    career_phase_raw = _resolve_career_phase(payload)
    career_phase = _career_phase_label(age_stage, career_phase_raw)
    chart_facts = _build_chart_signature_facts(payload, active_lord, peak_lord)
    macro_clusters = _macro_cluster_ranking(results, top_n=20)

    llm_meta = {
        "attempted": False,
        "succeeded": False,
        "provider": "",
        "model": "",
        "error_message": "LLM report not attempted (consent or API key missing)",
    }
    if _llm_consent:
        report, llm_meta = _call_llm_for_report(
            name, career_phase, active_lord, peak_lord, chart_facts, results, macro_clusters,
        )
    else:
        logger.info("[PRIVACY] External report LLM skipped: explicit consent not supplied.")
        report = None
    if not report:
        logger.warning(
            "[career_field_report_v2] LLM report generation failed/unavailable — using deterministic fallback."
        )
        report = _fallback_report_json(results, macro_clusters, name)

    report = _apply_deterministic_suitability_to_report(report, results)
    report["privacy"] = privacy_contract(payload)
    report["calculation_identity"] = calculation_identity(
        build_policy_json(), engine=ENGINE_VERSION, degraded=False,
    )

    bundle: Dict[str, Any] = {
        "payload": payload,
        "results": results,
        "report": report,
        "macro_clusters": macro_clusters,
        "chart_facts": chart_facts,
        "active_lord": active_lord,
        "peak_lord": peak_lord,
        "career_phase": career_phase,
        "name": name,
        "llm_meta": llm_meta,
    }

    if render_html:
        try:
            html = render_report_html_rich(
                name, career_phase, active_lord, peak_lord, results, macro_clusters, report, chart_facts,
            )
            if not html or "<body" not in html.lower():
                raise RuntimeError("render_report_html_rich returned empty/invalid HTML")
        except Exception as rich_err:
            logger.warning("[career_field_report_v2] Rich renderer failed (%s) — plain fallback.", rich_err)
            html = render_report_html(
                name, career_phase, active_lord, peak_lord, results, macro_clusters, report, chart_facts,
            )
        os.makedirs(output_dir, exist_ok=True)
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        safe_name = name.lower().replace(" ", "_")
        out_path = os.path.join(output_dir, f"career_field_report_{safe_name}_{ts}.html")
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(html)
        bundle["html_path"] = out_path

    return bundle


def generate_career_field_report_v2(
    chart_path: str,
    student_name: Optional[str] = None,
    output_dir: str = "educational_records",
    enable_llm_field_explanations: bool = False,
    use_new_renderer: bool = False,
    precomputed_results: Optional[List[Dict[str, Any]]] = None,
    peak_dasha_lord: Optional[str] = None,
) -> str:
    """Run the engine on a chart JSON file and write the 14-section
    Career Field Recommendation Report as a standalone HTML file.

    Parameters
    ----------
    chart_path:
        Path to a JyotishAI chart JSON.
    student_name:
        Override name; falls back to the payload's own name field.
    output_dir:
        Directory to write the HTML report to.
    enable_llm_field_explanations:
        If True, also runs the engine's own per-field LLM explanation pass.
        The v2 report does not require this because it performs one report-level
        narrative call, so default is False.
    use_new_renderer:
        Default is False. The Jinja2 renderer is timeline-period oriented and
        should not be used for the Top-20 field report unless explicitly needed.
        When True, it is attempted only if payload.career_timeline exists.
        Empty/invalid HTML from that path is rejected.
    precomputed_results:
        Optional authoritative rows from a caller that already ran the engine.
        When supplied, the report reuses them exactly instead of rerunning and
        risking a different Top 20.
    peak_dasha_lord:
        Bug fix (2026-08-17, user-flagged "CLI gives Saturn, HTML gives
        Jupiter"): payload.peak_dasha_lord is set as a SIDE EFFECT inside
        run_engine() (engine.py:1911), not by parse_json_payload(). When a
        caller supplies `precomputed_results` (skipping the run_engine()
        call below), this function still builds its OWN fresh `payload` from
        chart_path just above -- a different object from whatever payload
        the caller's own run_engine() call already computed peak_dasha_lord
        on. That fresh payload never got peak_dasha_lord set, so line ~3199
        silently fell back to active_lord (the CURRENT dasha, e.g. Jupiter)
        instead of the real peak dasha (e.g. Saturn) the caller's own CLI
        run already computed and logged as "Peak career MD". Callers that
        already ran run_engine() themselves (e.g. education_engine.py) must
        pass that payload's peak_dasha_lord through here explicitly so both
        outputs describe the same chart the same way.

    Returns
    -------
    Path to the written HTML file.
    """
    with open(chart_path, "r", encoding="utf-8") as fh:
        data = json.load(fh)

    payload = parse_json_payload(data, chart_path=chart_path)
    name = student_name or getattr(payload, "name", "Unknown")

    logger.info("[career_field_report_v2] Preparing report for %s...", name)
    # LLM usage can be granted per-chart (student_context.external_llm_consent
    # in the chart JSON) or globally via the LLM_REPORT_CONSENT env var
    # (.env). The env var is a blanket on/off switch for every report run in
    # this environment; the per-chart flag still works on its own for callers
    # who want consent scoped to a single student rather than the whole box.
    _env_llm_consent = str(os.getenv("LLM_REPORT_CONSENT", "")).strip().lower() in {"1", "true", "yes", "on"}
    _llm_consent = bool(getattr(payload, "external_llm_consent", False)) or _env_llm_consent
    if _env_llm_consent:
        logger.info("[career_field_report_v2] LLM consent granted via LLM_REPORT_CONSENT env var.")
    if enable_llm_field_explanations and not _llm_consent:
        logger.warning("[PRIVACY] Per-field LLM explanations disabled: external_llm_consent is false.")
    if precomputed_results is None:
        results = run_engine(payload, enable_llm=bool(enable_llm_field_explanations and _llm_consent))
    else:
        # Freeze the caller's authoritative engine result.  Copy before report
        # annotations so SBC/suitability metadata cannot mutate CLI/API rows.
        results = deepcopy(precomputed_results)
        logger.info("[career_field_report_v2] Reusing %d precomputed engine rows.", len(results))

    # Slim rows to render-relevant keys only (2026-07-18, user request).
    # Engine rows carry ~100 keys per field, ~95% of which is a calc/audit
    # trail (method_log, calc_trace, evidence_ledger_v2, gap_detail, ...)
    # that nothing in this report pipeline reads -- verified by grepping
    # every row/r.get(...) call in this file, sbc.py, and field_suitability.py.
    # Dropping it here (before the SBC/suitability/LLM-prompt/HTML steps that
    # all consume `results`) cuts per-run memory/JSON-serialization size for
    # this pipeline by roughly 20x without changing any rendered output.
    # If a future report/audit section needs a dropped field, add it to
    # RENDER_KEYS in Field_Determination/debug_payload_split.py rather than
    # reverting this slim step.
    from Field_Determination.debug_payload_split import slim_for_render
    results = slim_for_render(results)

    # SBC advisory layer only. Never overwrite deterministic ranking with SBC ranking.
    try:
        from .sbc import SarvatobhadraEngine

        sbc_results = SarvatobhadraEngine(payload).apply_to_ranking([dict(r) for r in results])

        sbc_by_id: Dict[str, Dict[str, Any]] = {}
        for srow in sbc_results:
            skey = (
                srow.get("field_id")
                or srow.get("branch_id")
                or srow.get("id")
                or srow.get("key")
                or _field_display_name(srow)
            )
            sbc_by_id[str(skey)] = srow

        for r in results:
            rkey = (
                r.get("field_id")
                or r.get("branch_id")
                or r.get("id")
                or r.get("key")
                or _field_display_name(r)
            )
            s = sbc_by_id.get(str(rkey), {})
            r["sbc_manifestation"] = {
                "smi": s.get("smi"),
                "timing_band": s.get("timing_band"),
                "sbc_notes": s.get("sbc_notes", []),
                "advisory_only": True,
            }

        logger.info(
            "SBC advisory layer applied to %d fields. Aptitude ranking preserved.",
            len(results),
        )

    except Exception as sbc_err:
        logger.warning("[career_field_report_v2] SBC advisory layer unavailable: %s", sbc_err)

    # Ranking policy is owned by run_engine().  Reports may annotate rows but
    # must never rescore or reorder them independently.

    # Professional route-suitability layer. Attach canonical registry metadata
    # before assessment because engine rows intentionally keep that data lean.
    registry_v12 = _load_course_registry()
    for row in results:
        fid = _row_field_id(row)
        meta = registry_v12.get(fid, {}) if fid else {}
        row["registry_v12"] = _v12_registry_slice(meta)
        for key in ("education_realism", "curriculum", "market", "risk", "routes"):
            if not row.get(key) and isinstance(meta.get(key), dict):
                row[key] = meta[key]

    student_ctx = data.get("student_context", {}) or {}
    preference = student_ctx.get("student_preference", {}) or {}
    academic_profile = (
        student_ctx.get("academic_profile")
        or preference.get("academic_profile")
        or preference.get("subject_scores")
        or {}
    )
    results = annotate_field_suitability(
        results,
        academic_profile=academic_profile,
        risk_appetite=getattr(payload, "risk_appetite", "MODERATE"),
    )
    for rank, row in enumerate(results[:20], 1):
        assessment = row.get("recommendation_assessment", {})
        logger.info(
            "[SUITABILITY] rank=%02d field=%s status=%s overall=%.2f "
            "astro=%.2f academic=%s education=%.2f career=%.2f "
            "conditions=%s contraindications=%s missing=%s",
            rank, _field_display_name(row), assessment.get("recommendation_status", ""),
            float(assessment.get("overall_suitability", 0.0)),
            float(assessment.get("astrological_alignment", 0.0)),
            "unknown" if assessment.get("academic_fit") is None else f'{float(assessment.get("academic_fit")):.2f}',
            float(assessment.get("education_feasibility", 0.0)),
            float(assessment.get("career_viability", 0.0)),
            assessment.get("conditions", []), assessment.get("contraindications", []),
            assessment.get("missing_validations", []),
        )

    current_age = float(getattr(payload, "current_age", 0) or 0)
    active_lord = _get_active_dasha_lord(getattr(payload, "dasha_sequence", []), current_age)
    # Prefer the caller-supplied peak_dasha_lord (from a payload that
    # actually went through run_engine()) over this function's own fresh
    # `payload`, which never ran run_engine() when precomputed_results is
    # supplied and so never got peak_dasha_lord set — see the
    # peak_dasha_lord parameter docstring above.
    peak_lord = peak_dasha_lord or getattr(payload, "peak_dasha_lord", "") or active_lord
    age_stage = classify_age_stage(current_age, results)
    career_phase_raw = _resolve_career_phase(payload)
    career_phase = _career_phase_label(age_stage, career_phase_raw)
    chart_facts = _build_chart_signature_facts(payload, active_lord, peak_lord)
    chart_facts["education_intent"] = _resolve_education_intent(data, current_age)
    macro_clusters = _macro_cluster_ranking(results, top_n=20)

    # Single source of truth for the headline UG/PG/backup/alternate-backup
    # routes — computed once, before the LLM call, so both the LLM prompt and
    # the deterministic fallback narrate the exact same selection. See
    # _select_headline_routes() for the rules.
    #
    # Bug fix (2026-08-17, user-flagged: "Technology Consulting"/"Economics"
    # shown as the headline UG/backup even though neither appears in the
    # published Top 20 table): this used to pass the FULL, unsliced `results`
    # population (every scored field in the ~205-field registry, not just
    # the ones actually published in the report) into _select_headline_
    # routes(). Its validated_recommendation_rank-based selection could then
    # legitimately pick a field ranked #21 or #31 overall -- one the reader
    # can never see or cross-check, since every other section of this report
    # (Top 20 table, cluster panels, method-score canvas) is built from
    # results[:20]/[:35] only. A headline pick that isn't even visible in the
    # report it headlines is a credibility bug on its own, regardless of how
    # defensible its suitability score is. Capping the candidate pool to the
    # same top20 the reader actually sees guarantees the headline selection
    # is always a field the reader can find and verify in this same report.
    locked_routes = _select_headline_routes(results[:20])
    logger.info(
        "[career_field_report_v2] Locked headline selection: ug=%s pg=%s backup=%s alt_backup=%s",
        locked_routes.get("ug_label"), locked_routes.get("pg_label"),
        locked_routes.get("backup_label"), locked_routes.get("alt_backup_label"),
    )

    if _llm_consent:
        report = _call_llm_for_report(
            name, career_phase, active_lord, peak_lord, chart_facts, results, macro_clusters,
            locked=locked_routes,
        )
    else:
        logger.info("[PRIVACY] External report LLM skipped: explicit consent not supplied.")
        report = None

    if not report:
        logger.warning(
            "[career_field_report_v2] LLM report generation failed/unavailable — using deterministic fallback."
        )
        report = _fallback_report_json(
            results, macro_clusters, name, chart_facts.get("education_intent", "first_ug_selection"),
            locked=locked_routes,
        )

    # Re-assert the locked UG/PG/backup selection regardless of what the LLM
    # (or the fallback) actually wrote — see _enforce_deterministic_headline().
    report = _enforce_deterministic_headline(report, locked_routes)

    # Deterministic policy owns status labels even when narrative text came
    # from an LLM. This prevents unsupported LLM demotions or resurrection of
    # the former parent_safe=False shortcut.
    report = _apply_deterministic_suitability_to_report(report, results, locked=locked_routes)
    report["privacy"] = privacy_contract(payload)
    report["calculation_identity"] = calculation_identity(
        build_policy_json(), engine=ENGINE_VERSION, degraded=False,
    )

    html: Optional[str] = None

    if use_new_renderer:
        timeline_periods = getattr(payload, "career_timeline", None)
        if timeline_periods:
            try:
                from jyotish.report_renderer import render_career_report

                raw_view = {
                    "context": {
                        "employment_status": getattr(payload, "employment_status", ""),
                        "designation": name,
                    },
                    "chart": chart_facts or {},
                    "periods": timeline_periods,
                }
                html = render_career_report(raw_view)

                if not html or not str(html).strip() or "<body" not in str(html).lower():
                    logger.warning(
                        "[career_field_report_v2] New Jinja renderer returned empty/invalid HTML; "
                        "forcing field-report renderer fallback."
                    )
                    html = None
                else:
                    logger.info("[career_field_report_v2] Rendered with timeline/Jinja renderer path.")

            except Exception as new_render_err:
                logger.warning(
                    "[career_field_report_v2] New renderer failed (%s) — falling back to field renderer.",
                    new_render_err,
                )
                html = None
        else:
            logger.info(
                "[career_field_report_v2] use_new_renderer=True but payload has no career_timeline; "
                "using field-report renderer."
            )

    if html is None:
        try:
            html = render_report_html_rich(
                name,
                career_phase,
                active_lord,
                peak_lord,
                results,
                macro_clusters,
                report,
                chart_facts,
            )

            logger.info(
                "[career_field_report_v2] rich renderer returned type=%s len=%s has_body=%s",
                type(html).__name__,
                len(html) if isinstance(html, str) else None,
                ("<body" in html.lower()) if isinstance(html, str) else False,
            )

            if not html or not str(html).strip() or "<body" not in str(html).lower():
                raise RuntimeError("render_report_html_rich returned empty/invalid HTML")

        except Exception as rich_err:
            logger.warning(
                "[career_field_report_v2] Rich field-report renderer failed (%s) — falling back to plain renderer.",
                rich_err,
            )

            html = render_report_html(
                name,
                career_phase,
                active_lord,
                peak_lord,
                results,
                macro_clusters,
                report,
                chart_facts,
            )

            if not html or not str(html).strip() or "<body" not in str(html).lower():
                raise RuntimeError("Both rich and plain field-report renderers returned empty/invalid HTML")

    os.makedirs(output_dir, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = name.lower().replace(" ", "_")
    out_path = os.path.join(output_dir, f"career_field_report_{safe_name}_{ts}.html")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(html)

    logger.info(
        "[career_field_report_v2] Wrote report -> %s bytes=%d has_body=%s has_v12=%s",
        out_path,
        len(html.encode("utf-8")),
        "<body" in html.lower(),
        "registry_v12" in html,
    )

    return out_path
