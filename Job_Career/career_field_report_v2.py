def _row_section(row: Dict[str, Any], key: str) -> Dict[str, Any]:
    """Read a v12 metadata section off a ranked field row, checking both the
    flattened key and the nested registry_v12 payload."""
    if not row:
        return {}
    rv12 = row.get("registry_v12", {}) or {}
    value = row.get(key) or rv12.get(key) or {}
    return value if isinstance(value, dict) else {}


def _select_pg_route_row(top35: List[Dict], primary_row: Dict[str, Any] | None = None) -> Dict[str, Any]:
    """Pick the field that is actually the best PG/specialization route.

    Rank position alone is not evidence of a PG route: the deterministic
    top-3-by-astrology field may not need PG at all, and a field that *does*
    need PG (education_realism.pg_required_for_good_outcome) may sit at any
    rank. This walks the ranked list in order and returns the first field
    that (a) is not the UG primary field, (b) is flagged as PG-dependent,
    and (c) has not been rejected outright (STATUS_NOT_PRIMARY). Only if no
    such field exists does it fall back to the historical rank-3 behavior,
    and finally to the primary field itself.
    """
    primary_label = _field_display_name(primary_row) if primary_row else ""
    for row in top35 or []:
        if not isinstance(row, dict):
            continue
        if _field_display_name(row) == primary_label:
            continue
        edu = _row_section(row, "education_realism")
        if not edu.get("pg_required_for_good_outcome"):
            continue
        status = (row.get("recommendation_assessment") or {}).get("recommendation_status", "")
        if status == STATUS_NOT_PRIMARY:
            continue
        return row
    # No field is actually flagged as PG-dependent: fall back to the old
    # rank-3 placeholder (kept only for schema continuity), then rank-1.
    if top35 and len(top35) > 2:
        return top35[2]
    return (top35[0] if top35 else {}) or {}


