def _build_report_user_prompt(
    student_name: str,
    career_phase: str,
    active_lord: str,
    peak_lord: str,
    chart_facts: Dict[str, Any],
    top35: List[Dict],
    macro_clusters: List[Dict],
) -> str:
    field_lines = []
    for rank, r in enumerate(top35[:35], 1):
        field_lines.append({
            "rank": rank,
            "field_label": _field_display_name(r),
            "domain": r.get("domain", ""),
            "final_score": round(float(r.get("final_score", 0.0) or 0.0), 3),
            "macro_cluster": _print_macro_cluster(r),
        })

    return f"""--- STUDENT / CLIENT ---
Name: {student_name}
Career phase: {career_phase}
Active Mahadasha lord: {active_lord}
Peak career Mahadasha lord: {peak_lord}

--- RAW CHART FACTS (do not contradict) ---
{json.dumps(chart_facts, indent=2, default=str)}

--- ENGINE MACRO-CLUSTER RANKING (top 20, already computed — do not change strengths) ---
{json.dumps(macro_clusters, indent=2)}

--- ENGINE TOP-35 FIELDS (deterministic ranking + scores — do not change ranks/scores) ---
{json.dumps(field_lines, indent=2)}

Using ONLY the fields, clusters, and facts above, produce the JSON object described in the system prompt.
"""


def _validate_report_json(data: Dict) -> None:
    required = [
        "final_identity", "snapshot", "astrological_signature",
        "macro_cluster_interpretations", "top_20_fields", "education_routes",
        "fields_to_avoid", "engine_output_comparison", "engine_gap_audit",
        "parent_summary", "student_summary", "final_recommendation",
    ]
    missing = [k for k in required if k not in data]
    if missing:
        raise ValueError(f"Missing required keys: {missing}")


def _call_llm_for_report(
    student_name: str,
    career_phase: str,
    active_lord: str,
    peak_lord: str,
    chart_facts: Dict[str, Any],
    top35: List[Dict],
    macro_clusters: List[Dict],
) -> Optional[Dict]:
    """Single structured LLM call producing every narrative/judgement field in the report."""
    try:
        from .engine_io import _maybe_load_dotenv as _dotenv_fn
        _dotenv_fn()
    except Exception:
        pass

    provider_name = os.getenv("LLM_PROVIDER", "gemini").lower()
    env_var, default_model, call_fn = _LLM_PROVIDERS.get(provider_name, _LLM_PROVIDERS["gemini"])
    model_override = os.getenv("LLM_MODEL", default_model)
    api_key = os.getenv(env_var)
    if not api_key:
        logger.warning("%s missing (provider=%s) — report will use deterministic fallback text.", env_var, provider_name)
        return None

    client = _ProviderClientWrapper(call_fn, api_key, model_override)
    user_prompt = _build_report_user_prompt(
        student_name, career_phase, active_lord, peak_lord, chart_facts, top35, macro_clusters
    )
    messages = [
        {"role": "system", "content": _REPORT_SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]
    schema = {"schema": {"required": [], "properties": {}}}  # structure hint embedded in system prompt already
    return _run_llm_with_retry(client, messages, schema, _validate_report_json, max_retries=3)


