def render_report_html(
    student_name: str,
    career_phase: str,
    active_lord: str,
    peak_lord: str,
    top35: List[Dict],
    macro_clusters: List[Dict],
    report: Dict,
    chart_facts: Optional[Dict[str, Any]] = None,
) -> str:
    """Canonical dashboard HTML for all career-field report outputs."""
    gen_date = datetime.now().strftime("%d %b %Y, %H:%M")
    fi = report.get("final_identity", {}) or {}
    snap = report.get("snapshot", {}) or {}
    chart_facts = chart_facts or {}

    def score_value(row: Dict) -> float:
        return round(float((row or {}).get("final_score", 0.0) or 0.0), 2)

    def score_text(row: Dict) -> str:
        return f"{score_value(row):.2f}"

    def score_width(row: Dict) -> float:
        return max(0.0, min(100.0, score_value(row)))

    def level_class(level: str) -> str:
        l = (level or "").lower()
        if "primary" in l:
            return "primary"
        if "strong" in l or "special" in l:
            return "strong"
        if "backup" in l or "pg" in l:
            return "backup"
        return "explore"

    def split_options(text: Any) -> List[str]:
        raw = str(text or "").replace(";", ",")
        return [p.strip() for p in raw.split(",") if p.strip()]

    def pills(items: List[str], cls: str = "") -> str:
        klass = f"pill {cls}".strip()
        return "".join(f'<span class="{klass}">{_esc(i)}</span>' for i in items if str(i or "").strip())

    top1 = top35[0] if top35 else {}
    top2 = top35[1] if len(top35) > 1 else {}
    top3 = top35[2] if len(top35) > 2 else {}
    top1_label = _field_display_name(top1) if top1 else (snap.get("best_ug_route") or "Undetermined")
    top2_label = _field_display_name(top2) if top2 else (snap.get("strong_backup_route") or "")
    top3_label = _field_display_name(top3) if top3 else (snap.get("best_pg_route") or "")
    top_cluster = macro_clusters[0] if macro_clusters else {"cluster": fi.get("macro_identity", ""), "strength_pct": 0}
