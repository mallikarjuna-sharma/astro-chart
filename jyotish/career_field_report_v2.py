def _macro_cluster_ranking(results: List[Dict], top_n: int = 20) -> List[Dict]:
    """Group the top-N fields by macro-cluster and rank clusters by weighted score."""
    grouped: Dict[str, List[Dict]] = {}
    order: List[str] = []
    for rank, row in enumerate(results[:top_n], 1):
        cluster = _print_macro_cluster(row)
        grouped.setdefault(cluster, []).append({**row, "_rank": rank})
        if cluster not in order:
            order.append(cluster)

    def _cluster_strength(rows: List[Dict]) -> float:
        # Weighted by rank position (higher rank = more weight) and final_score.
        return sum((top_n + 1 - r["_rank"]) * float(r.get("final_score", 0.0) or 0.0) for r in rows)

    ranked = sorted(
        ((c, grouped[c]) for c in order),
        key=lambda kv: -_cluster_strength(kv[1]),
    )
    max_strength = _cluster_strength(ranked[0][1]) if ranked else 1.0
    out = []
    for i, (cluster, rows) in enumerate(ranked, 1):
        strength = _cluster_strength(rows)
        pct = round(100 * strength / max_strength, 0) if max_strength else 0
        out.append({
            "rank": i,
            "cluster": cluster,
            "strength_pct": pct,
            "member_fields": [_field_display_name(r) for r in rows],
            "best_rank_in_cluster": min(r["_rank"] for r in rows),
        })
    return out


def _build_chart_signature_facts(payload: NatalPayloadV2, active_lord: str, peak_lord: str) -> Dict[str, Any]:
    """Pull the raw chart facts (no interpretation) that the LLM will explain."""
    house_lords = getattr(payload, "house_lords", {}) or {}
    dob = getattr(payload, "dob", "") or ""
    ug_start_year = ""
    try:
        # Indian UG admission normally follows the Class 12 year. Students born
        # after the Sep admission cutoff usually join in the next calendar year.
        birth_dt = datetime.strptime(str(dob), "%Y-%m-%d")
        ug_start_year = birth_dt.year + (19 if birth_dt.month >= 10 else 18)
    except Exception:
        current_age = float(getattr(payload, "current_age", 0) or 0)
        if current_age:
            ug_start_year = datetime.now().year + max(0, int(round(18 - current_age)))
    return {
        "lagna_sign": getattr(payload, "lagna_sign", "") or getattr(payload, "ascendant_sign", ""),
        "h10_lord": house_lords.get(10, house_lords.get("10", "")),
        "active_mahadasha_lord": active_lord,
        "peak_career_mahadasha_lord": peak_lord,
        "dob": dob,
        "current_age": getattr(payload, "current_age", 0),
        "ug_start_year": ug_start_year,
        "eff_strengths_top3": sorted(
            (getattr(payload, "eff_strengths", {}) or {}).items(), key=lambda x: -x[1]
        )[:3],
        "arudha_lagna": getattr(payload, "arudha_lagna", ""),
        "arudha_pada_h10": getattr(payload, "arudha_pada_h10", ""),
        "academic_tier_recommendation": getattr(payload, "academic_tier_recommendation", {}) or {},
        "edu_stream": getattr(payload, "edu_stream", {}) or {},
    }


def _career_phase_label(age_stage: Dict, career_phase_raw: str) -> str:
    stage = age_stage.get("stage", "")
    mapping = {
        "class_9_10": "Class 9-10",
        "class_11_12": "Class 11-12",
        "adult": career_phase_raw.replace("_", " ").title() if career_phase_raw else "Working Professional",
    }
    return mapping.get(stage, career_phase_raw.replace("_", " ").title() if career_phase_raw else "Adult")


