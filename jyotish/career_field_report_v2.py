def _build_career_field_report_bundle(
    data: Dict[str, Any],
    student_name: Optional[str] = None,
    use_new_renderer: bool = True,
) -> Dict[str, Any]:
    """Run engine + SBC + LLM narrative and render the career field report HTML."""
    payload = parse_json_payload(data)
    name = student_name or getattr(payload, "name", "Unknown")

    logger.info("[career_field_report_v2] Running engine for %s...", name)
    results = run_engine(payload)

    try:
        from .sbc import SarvatobhadraEngine
        results = SarvatobhadraEngine(payload).apply_to_ranking(results)
    except Exception as sbc_err:
        logger.warning("[career_field_report_v2] SBC advisory layer unavailable: %s", sbc_err)

    current_age = float(getattr(payload, "current_age", 0) or 0)
    active_lord = _get_active_dasha_lord(getattr(payload, "dasha_sequence", []), current_age)
    peak_lord = getattr(payload, "peak_dasha_lord", "") or active_lord
    age_stage = classify_age_stage(current_age, results)
    career_phase_raw = _resolve_career_phase(payload)
    career_phase = _career_phase_label(age_stage, career_phase_raw)
    chart_facts = _build_chart_signature_facts(payload, active_lord, peak_lord)
    macro_clusters = _macro_cluster_ranking(results, top_n=20)

    report = _call_llm_for_report(name, career_phase, active_lord, peak_lord, chart_facts, results, macro_clusters)
    if not report:
        logger.warning(
            "[career_field_report_v2] LLM report generation failed/unavailable — using deterministic fallback."
        )
        report = _fallback_report_json(results, macro_clusters, name)

    html = None
    if use_new_renderer:
        _timeline_periods = getattr(payload, "career_timeline", None)
        if _timeline_periods:
            try:
                from .report_renderer import render_career_report
                _raw_view = {
                    "context": {
                        "employment_status": getattr(payload, "employment_status", ""),
                        "designation": name,
                    },
                    "chart": chart_facts or {},
                    "periods": _timeline_periods,
                }
                html = render_career_report(_raw_view)
                logger.info("[career_field_report_v2] Rendered with new report_renderer (Jinja2) path.")
            except Exception as new_render_err:
                logger.warning(
                    "[career_field_report_v2] New renderer failed (%s) — falling back to legacy render_report_html.",
                    new_render_err,
                )
                html = None
        else:
            logger.info(
                "[career_field_report_v2] No timeline periods on payload — using legacy renderer "
                "(new renderer targets timeline-period reports; the 14-section field-ranking "
                "report has no period-level view model to build)."
            )

    if html is None:
        try:
            html = render_report_html_rich(name, career_phase, active_lord, peak_lord, results, macro_clusters, report, chart_facts)
        except Exception as _rich_err:
            logger.warning(
                "[career_field_report_v2] Rich field-report renderer failed (%s) — "
                "falling back to plain sec-title renderer.", _rich_err
            )
            html = render_report_html(name, career_phase, active_lord, peak_lord, results, macro_clusters, report, chart_facts)

    return {
        "student_name": name,
        "career_phase": career_phase,
        "active_lord": active_lord,
        "peak_lord": peak_lord,
        "results": results,
        "macro_clusters": macro_clusters,
        "report": report,
        "chart_facts": chart_facts,
        "html": html,
        "payload": payload,
    }


def build_career_field_report_from_chart(
    chart: Dict[str, Any],
    student_name: Optional[str] = None,
) -> Dict[str, Any]:
    """Build the career field report from consolidated chart JSON (API / web use)."""
    return _build_career_field_report_bundle(chart, student_name=student_name)


def generate_career_field_report_v2(
    chart_path: str,
    student_name: Optional[str] = None,
    output_dir: str = "educational_records",
    enable_llm_field_explanations: bool = False,
    use_new_renderer: bool = True,
) -> str:
    """Run the engine on a chart JSON file and write the 14-section
    Career Field Recommendation Report as a standalone HTML file.

    Parameters
    ----------
    chart_path : path to a JyotishAI chart JSON (same format as export_field_summaries.py)
    student_name : override name; falls back to the payload's own `name` field
    output_dir : directory to write the HTML report to
    enable_llm_field_explanations : if True, also runs the engine's own
        per-field LLM explanation pass (slower, extra LLM calls) — the new
        report format does not require this since it does its own narrative
        pass, so default is False.

    use_new_renderer : if True (default), attempt the new Jinja2-templated
        renderer (jyotish/report_renderer.py, Phase 4 of the 2026-07 career
        report refactor) when the payload carries timeline period data
        (payload.career_timeline). Falls back to the legacy render_report_html
        renderer automatically if no timeline periods are present, or if the
        new renderer raises for any reason — the legacy path is always the
        safety net and is never removed.

    Returns
    -------
    The path to the written HTML file.
    """
    with open(chart_path, "r", encoding="utf-8") as fh:
        data = json.load(fh)

    bundle = _build_career_field_report_bundle(
        data,
        student_name=student_name,
        use_new_renderer=use_new_renderer,
    )
    html = bundle["html"]
    name = bundle["student_name"]

    os.makedirs(output_dir, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = name.lower().replace(" ", "_")
    out_path = os.path.join(output_dir, f"career_field_report_{safe_name}_{ts}.html")
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(html)

    logger.info("[career_field_report_v2] Wrote report -> %s", out_path)
    return out_path
