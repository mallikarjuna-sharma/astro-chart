"""jyotish/career_field_report_v2.py — Parent/Student-Friendly Career Field
Recommendation Report (14-section format).

This module produces the exact report structure requested by the user:
  1. Executive Summary
  2. Final Recommendation Snapshot
  3. Astrological Career Signature
  4. Final Macro-Cluster Ranking
  5. Corrected Top 20 Fields
  6. Education Route Mapping (3 routes: Primary / High-End Specialised / Safe Backup)
  7. Fields to Avoid as Primary
  8. Engine Output Comparison (raw engine rank vs corrected/final status)
  9. Engine Gap Diagnosis
  10. Final Student-Friendly Recommendation
  11. Parent Report Version
  12. Student Version
  13. (JSON schema — embedded as <script type="application/json"> in the HTML)
  14. Fixed section order (enforced by this file's rendering order)

Design
------
Everything that is DETERMINISTIC (scores, ranks, dasha lords, macro-cluster
membership, age-based career phase) comes straight from the existing engine
(`jyotish.engine.run_engine`) — nothing is re-invented or guessed.

Everything that requires JUDGEMENT / NARRATIVE — the one-line career identity,
the astrological-signature interpretation, education-route mapping, the
avoid-list reasoning, the engine-gap audit, and the parent/student prose — is
explicitly marked "LLM" per the user's instruction, and is generated by a
single structured call to the already-configured LLM provider
(jyotish/llm.py — Gemini by default, Anthropic/OpenAI as configured in .env).

If no LLM API key is configured, the report is still produced with clearly
labelled deterministic fallbacks so the file never silently omits a section.
"""
