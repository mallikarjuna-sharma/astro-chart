def parse_validation_response(raw_json: str) -> Dict:
    """Parse a raw Step 1 JSON string into a dict. Raises ValueError on failure."""
    try:
        result = json.loads(raw_json)
    except json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON from validator LLM: {exc}") from exc
    required_keys = {
        "validator_version", "summary", "event_matches",
        "predicted_misses", "engine_gaps", "factor_attribution",
        "engine_improvements", "data_quality_flags",
    }
    missing = required_keys - set(result.keys())
    if missing:
        raise ValueError(f"Validator response missing required keys: {missing}")
    return result


