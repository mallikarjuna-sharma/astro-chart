def extract_actual_history_from_payload(payload: Any) -> List[Dict]:
    """
    Extract the user's actual career event history from a NatalPayloadV2.

    The engine stores actual past events in two places:
      1. career_context["career_events"]  — list of {date, event_type, role, company, notes}
      2. career_context legacy fields     — join_date, last_promotion_date, last_hike_date

    Returns a list of dicts compatible with build_validator_user_message(), each with:
      {date, description, company, intensity}
    """
    def _g(key: str, default: Any = None) -> Any:
        if isinstance(payload, dict):
            return payload.get(key, default)
        return getattr(payload, key, default)

    cc = _g("career_context", {}) or {}
    events: List[Dict] = []

    # 1. Full career_events list
    for evt in (cc.get("career_events") or []):
        if not isinstance(evt, dict):
            continue
        d = evt.get("date", "")
        if not d:
            continue
        desc = (evt.get("description")
                or evt.get("notes")
                or evt.get("event_type", "Career event").replace("_", " ").title())
        role = evt.get("role", "")
        if role and role not in desc:
            desc = f"{role} — {desc}"
        events.append({
            "date":        d[:7],          # YYYY-MM
            "description": desc,
            "company":     evt.get("company", ""),
            "intensity":   evt.get("intensity", ""),
        })

    # 2. Legacy date fields
    legacy = [
        ("join_date",           "Joined current company"),
        ("last_promotion_date", "Last promotion"),
        ("last_hike_date",      "Last salary hike"),
    ]
    for field, label in legacy:
        d = cc.get(field, "")
        if d and not any(e["date"] == d[:7] for e in events):
            events.append({"date": d[:7], "description": label, "company": "", "intensity": ""})

    # Sort chronologically
    events.sort(key=lambda e: e.get("date", ""))
    return events


