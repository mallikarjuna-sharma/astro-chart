def _build_d10_devata_lines(d10_dd: Any) -> List[str]:
    """Format d10_devata_diagnostics dict into prompt lines."""
    if not d10_dd or not isinstance(d10_dd, dict):
        return ["  D10 devata data: not available"]
    lines: List[str] = []
    for key in ("unemployed", "salary_stagnant", "promotion_blocked", "sudden_halt"):
        entry = d10_dd.get(key)
        if not entry:
            continue
        label   = _D10_ARCHETYPE_LABEL.get(key, key.upper())
        body    = _D10_ARCHETYPE_BODY.get(key, "")
        lord    = entry.get("key_lord", "?")
        devata  = entry.get("devata", "?")
        sign    = entry.get("key_sign", "?")
        pivot   = entry.get("pivot_planet", "?")
        pivot_s = entry.get("pivot_sign_d10", "?")
        lines += [
            f"  {label}",
            f"    Pivot: {pivot} in {pivot_s} (D10)  →  {key.replace('_',' ').title()} house: {sign}  →  Lord: {lord}  →  Devata: {devata}",
            f"    {body}",
            "",
        ]
    return lines or ["  D10 devata data: not available"]

