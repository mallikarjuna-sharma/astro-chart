def call_validation_llm(
    payload: Any,
    predicted_blocks: List[Dict],
    actual_history: List[Dict],
    *,
    score_threshold: float = 0.55,
    model: str = "gpt-5.4-mini",
    temperature: float = 0.1,
    timeout: int = 120,
) -> Dict:
    """
    Run the two-step career validation pipeline against an LLM.

    Args:
        payload:           NatalPayloadV2 or dict.
        predicted_blocks:  Output of build_career_timeline()['blocks'].
        actual_history:    List of dicts [{date, description, company, intensity}, ...].
        score_threshold:   Minimum career_score to treat a block as a prediction.
        model:             OpenAI model string.
        temperature:       LLM temperature (low = deterministic).
        timeout:           Per-call timeout in seconds.

    Returns:
        dict with keys:
          "validation" : dict  (Step 1 structured output)
          "narrative"  : dict  (Step 2 report sections)
          "raw_step1"  : str
          "raw_step2"  : str
    """
    import openai

    api_key = os.environ.get("OPENAI_API_KEY", "")
    if not api_key:
        raise RuntimeError("OPENAI_API_KEY not set. Cannot call LLM for validation.")

    client = openai.OpenAI(api_key=api_key)

    chart_summary = build_chart_summary_for_validation(payload)
    user_msg_1    = build_validator_user_message(
        chart_summary, predicted_blocks, actual_history,
        score_threshold=score_threshold,
    )

    logger.info("[Validation] Step 1 — Validator call (%s)", model)

    resp1 = client.chat.completions.create(
        model=model,
        temperature=temperature,
        timeout=timeout,
        response_format={
            "type": "json_schema",
            "json_schema": _VALIDATOR_RESPONSE_SCHEMA,
        },
        messages=[
            {"role": "system",  "content": _VALIDATOR_SYSTEM_PROMPT},
            {"role": "user",    "content": user_msg_1},
        ],
    )
    raw1 = resp1.choices[0].message.content or ""

    try:
        validation_result = json.loads(raw1)
    except json.JSONDecodeError as exc:
        logger.error("[Validation] Step 1 JSON parse error: %s\nRaw: %s", exc, raw1[:300])
        validation_result = {"error": str(exc), "raw": raw1}

    logger.info(
        "[Validation] Step 1 complete — PAI_relaxed=%.2f  band=%s",
        validation_result.get("summary", {}).get("PAI_relaxed", 0.0),
        validation_result.get("summary", {}).get("confidence_band", "N/A"),
    )

    user_msg_2 = build_narrator_user_message(chart_summary, validation_result)

    logger.info("[Validation] Step 2 — Narrator call (%s)", model)

    resp2 = client.chat.completions.create(
        model=model,
        temperature=temperature,
        timeout=timeout,
        response_format={
            "type": "json_schema",
            "json_schema": _NARRATOR_RESPONSE_SCHEMA,
        },
        messages=[
            {"role": "system",  "content": _NARRATOR_SYSTEM_PROMPT},
            {"role": "user",    "content": user_msg_2},
        ],
    )
    raw2 = resp2.choices[0].message.content or ""

    try:
        narrative_result = json.loads(raw2)
    except json.JSONDecodeError as exc:
        logger.error("[Validation] Step 2 JSON parse error: %s\nRaw: %s", exc, raw2[:300])
        narrative_result = {"error": str(exc), "raw": raw2}

    return {
        "validation": validation_result,
        "narrative":  narrative_result,
        "raw_step1":  raw1,
        "raw_step2":  raw2,
    }


