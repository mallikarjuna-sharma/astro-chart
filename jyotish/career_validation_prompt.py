def build_validator_user_message(
    chart_summary: str,
    predicted_blocks: List[Dict],
    actual_history: List[Dict],
    score_threshold: float = 0.55,
) -> str:
    """
    Build the user message for the Step 1 validator call.

    Args:
        chart_summary:     Output of build_chart_summary_for_validation().
        predicted_blocks:  Career timeline blocks from build_career_timeline().
                           Each block should include: md_lord, ad_lord, start_date,
                           end_date, career_score, event_type, yoga_flags,
                           kp_cusp_score, enhancer_total_delta, and all enhancer
                           sub-fields (combustion_modifier, retrograde_modifier,
                           dig_bala_factor, vimsopaka_score, etc.)
        actual_history:    List of dicts with keys:
                             date (YYYY-MM), description (str),
                             intensity (0-10, optional), company (str, optional)
        score_threshold:   Career score above which a predicted block is considered
                           a "prediction" (blocks below this are background noise).

    Returns:
        str: The complete user message for Step 1.
    """
    # Filter to significant predicted blocks
    sig_blocks = [b for b in predicted_blocks if b.get("career_score", 0) >= score_threshold]
    # Include all blocks for context (engine sees full timeline)
    all_blocks = predicted_blocks

    # Compact block representation
    # NOTE: build_career_timeline() nests all _score_period sub-fields inside
    # block["sub_scores"]. The only top-level score field is "career_score".
    # Enhancer fields (vimsopaka_score, yogini_name, is_sandhi, event_hints, etc.)
    # are ALL inside sub_scores — not at the block's top level.
    def _fmt_block(b: Dict, idx: int) -> str:
        ss = b.get("sub_scores", {}) or {}   # ← all enhancer + sub-score fields live here
        signals = []
        # active_yogas is in sub_scores (set by _detect_natal_yogas via _score_period)
        yogas_list = ss.get("active_yogas", [])
        if yogas_list:
            signals.append(f"yogas={','.join(yogas_list[:3])}")
        # kp_cusp_score is in sub_scores
        kp = ss.get("kp_cusp_score", ss.get("kp_cusp_alignment", b.get("kp_cusp_alignment", 0)))
        if kp:
            signals.append(f"kp={kp:.2f}")
        # All enhancer fields are in sub_scores
        enh = ss.get("enhancer_total_delta", 0)
        if enh:
            signals.append(f"enh_delta={enh:+.3f}")
        for fk in ["vimsopaka_score", "chara_dasha_score", "yogini_score",
                   "d10_full_score", "kp_ssl_score"]:
            v = ss.get(fk, 0)
            if v:
                signals.append(f"{fk.split('_')[0]}={v:.2f}")
        # Yogini dasha name
        yog_name = ss.get("yogini_name", "")
        if yog_name:
            signals.append(f"yogini={yog_name}")
        for flag_key in ["nakshatra_triggers", "mars_aspect_flags", "transit_aspect_flags"]:
            fl = ss.get(flag_key, [])
            if fl:
                signals.append(f"{flag_key[:6]}={len(fl)}")

        line = (
            f"[{idx:02d}] {b.get('md_lord','?')}/{b.get('ad_lord','?')}  "
            f"{b.get('start_date','?')}→{b.get('end_date','?')}  "
            f"score={b.get('career_score',0):.3f}  "
            f"type={b.get('event_type','?')}"
        )
        if signals:
            line += f"  [{'; '.join(signals)}]"
        # Sandhi / risk flags — all in sub_scores
        extras = []
        if ss.get("is_sandhi"):
            extras.append("SANDHI")
        if ss.get("kala_sarpa_modifier", 0) < -0.01:
            extras.append("KALA_SARPA")
        if ss.get("papa_kartari_penalty", 0) < -0.01:
            extras.append("PAPA_KARTARI")
        event_hints = ss.get("event_hints", [])
        if event_hints:
            extras += event_hints[:2]
        if extras:
            line += f"  !{','.join(extras)}"
        return line

    blocks_text = "\n".join(_fmt_block(b, i) for i, b in enumerate(all_blocks, 1))

    # Actual history
    # Supports two formats:
    #   Validator format:     {date, description, company, intensity}
    #   career_events format: {date, event_type, role, company, notes}
    #
    # Gap-audit fix (2026-08): description/role/company/notes/event_type are
    # free-text fields sourced directly from the end user (this is the one
    # place in the LLM-integration layer where genuine user-supplied text
    # reaches a prompt, as opposed to the server-controlled structured data
    # used everywhere else in this file). Previously interpolated verbatim
    # with no escaping or length bound, which meant a user could: (a) embed
    # newlines + fake `[Axx]`/`━━━ ... ━━━` section markers to try to forge
    # additional history entries or spoof a new prompt section boundary,
    # confusing the structured [Axx]-index matching the validator LLM relies
    # on, or (b) submit an unbounded-length string to inflate token usage /
    # push other content out of context. _sanitize_user_text() below strips
    # control/newline characters (collapsing them to a single space, so a
    # multi-line "event description" still reads as one line and cannot
    # inject a fake delimiter/section boundary) and caps length. This does
    # not change any scoring/validation logic -- only how untrusted text is
    # embedded into the prompt string.
    def _fmt_event(e: Dict, idx: int) -> str:
        desc = (e.get("description")
                or e.get("notes")
                or e.get("event_type", "?").replace("_", " ").title())
        desc = _sanitize_user_text(desc)
        role = _sanitize_user_text(e.get("role", ""))
        if role and role not in desc:
            desc = f"{role} — {desc}"
        parts = [f"[A{idx:02d}]", e.get("date", "?"), "|", desc]
        co = _sanitize_user_text(e.get("company", ""))
        if co:
            parts += ["@", co]
        intensity = e.get("intensity", "")
        if intensity != "":
            parts += [f"intensity={intensity}/10"]
        return " ".join(str(p) for p in parts)

    history_text = "\n".join(_fmt_event(e, i) for i, e in enumerate(actual_history, 1))

    # Factor reference (for attribution analysis)
    factor_ref = ", ".join(_FACTOR_IDS)

    # Determine validation horizon from actual history dates
    _actual_dates = sorted(
        [e.get("date", "") for e in actual_history if e.get("date")],
    )
    _hist_start = _actual_dates[0]  if _actual_dates else "earliest available"
    _hist_end   = _actual_dates[-1] if _actual_dates else "latest available"

    user_msg = (
        f"{chart_summary}\n\n"
        f"━━━ ENGINE-PREDICTED CAREER TIMELINE ({len(all_blocks)} blocks, "
        f"{len(sig_blocks)} significant [score≥{score_threshold}]) ━━━\n"
        f"Format: [idx] MD/AD  start→end  score  type  [active signals]  !flags\n"
        f"{blocks_text}\n\n"
        f"━━━ ACTUAL CAREER HISTORY ({len(actual_history)} events, "
        f"spanning {_hist_start} → {_hist_end}) ━━━\n"
        f"Format: [Axx] YYYY-MM | description @ company  intensity=x/10\n"
        f"{history_text}\n\n"
        f"━━━ FACTOR ID REFERENCE (for factor_attribution output) ━━━\n"
        f"{factor_ref}\n\n"
        f"━━━ VALIDATION SCOPE (you decide) ━━━\n"
        f"You have been given the FULL dasha sequence from DOB and ALL predicted blocks "
        f"covering the person's career history (from {_hist_start}) through the forecast window. "
        f"Do NOT restrict your validation to any fixed number of years. "
        f"Validate every actual career event in the history above, regardless of how far back it "
        f"falls. The full Mahadasha + Antardasha sequence is in the chart summary — use it to "
        f"identify which MD/AD was active for each actual event, even those predating the "
        f"predicted-blocks window. For periods outside the predicted-blocks list, set "
        f"engine_score_for_period=null and root_cause='INSUFFICIENT_DATA' or the most accurate "
        f"alternative root cause you can derive from the dasha sequence alone.\n\n"
        f"━━━ TASK ━━━\n"
        f"Perform the 7-step validation as specified in the system prompt. "
        f"Return the complete JSON object. "
        f"Match each actual event [A01..A{len(actual_history):02d}] to the best predicted block. "
        f"Only blocks with score≥{score_threshold} count as active predictions for PAI/precision. "
        f"All 7 steps are mandatory."
    )
    return user_msg


