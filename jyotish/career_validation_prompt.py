def build_chart_summary_for_validation(payload: Any) -> str:
    """
    Build a concise chart summary string for the validation prompt.
    Mirrors _build_chart_summary_for_llm() in jyotish/llm.py.

    Args:
        payload: NatalPayloadV2 or any object / dict with standard chart fields.

    Returns:
        Multi-line string with all chart signals needed for validation.
    """
    def _g(key: str, default: Any = "not available") -> Any:
        if isinstance(payload, dict):
            return payload.get(key, default)
        return getattr(payload, key, default) or default

    def _fmt_planet_house(ph: Dict) -> str:
        if not ph:
            return "not available"
        return ", ".join(f"{p}→H{h}" for p, h in sorted(ph.items()) if h)

    def _fmt_dignities(digs: Any) -> str:
        if not digs:
            return "not available"
        if isinstance(digs, dict):
            parts = [f"{p}:{d}" for p, d in digs.items() if d]
            return ", ".join(parts) or "not available"
        return str(digs)

    # Core identifiers
    name          = _g("name", "Unknown")
    dob           = _g("dob", "not available")
    lagna         = _g("lagna_sign", "not available")
    ak            = _g("atmakaraka", "not available")
    amk           = _g("amatyakaraka", "not available")
    # Chara Karakas — now formal fields on NatalPayloadV2; fall back to
    # kn_rao_jaimini["chara_karakas"] for any legacy payload that lacks them.
    _kn_rao       = _g("kn_rao_jaimini", {}) or {}
    _cc           = (_kn_rao.get("chara_karakas") or {}) if isinstance(_kn_rao, dict) else {}
    mk            = _g("matrikaraka", "") or _cc.get("MK", "not available")
    bk            = _g("bhatrikaraka", "") or _cc.get("BK", "not available")
    pk            = _g("putrakaraka", "") or _cc.get("PK", "not available")
    gnk           = _g("gnatikaraka", "") or _cc.get("GnK", "not available")
    dk            = _g("darakaraka", "") or _cc.get("DK", "not available")

    planet_house  = _g("planet_house", {})
    house_lords   = _g("house_lords", {})
    # NatalPayloadV2 uses planet_signs (plural); "planet_sign" is a legacy alias
    planet_sign   = _g("planet_signs", {}) or _g("planet_sign", {}) or {}
    # NatalPayloadV2 uses planet_dignities (D1) and d9_planet_dignities (D9)
    dignities     = _g("planet_dignities", _g("dignities", {}))
    retrogrades   = _g("retrograde_planets", [])

    # KP data
    # CAVEAT (2026-08-21, remediation plan item 2.4, lower-priority): this KP
    # cusp data is fed to the LLM prompt as-is, with no birth-time-precision
    # or cusp-verification caveat attached — unlike the Tier 6 KP scoring
    # path in Job_Career/astro_enhancer.py, which now degrades its
    # contribution under birth-time uncertainty and unverified cusp chains
    # (see enhancer_score_delta()). Display/prompt text only (not scoring
    # math), so left as a flagged caveat here rather than changed, per the
    # remediation plan's explicit "more liberty here" scoping for this item.
    kp_cusps      = _g("kp_cusps", {}) or {}
    h10_kp        = kp_cusps.get("H10", {}) or {}
    h11_kp        = kp_cusps.get("H11", {}) or {}
    h6_kp         = kp_cusps.get("H6",  {}) or {}
    h2_kp         = kp_cusps.get("H2",  {}) or {}

    # Dasha — prefer the full sequence (with dates + ADs); fall back to stripped version
    _dasha_full   = _g("vimshottari_dasha_full", []) or []
    dasha_seq     = _dasha_full if _dasha_full else (_g("dasha_sequence", []) or [])
    current_age   = _g("current_age", "not available")

    # D9 — NatalPayloadV2 field is d9_planet_dignities (not d9_dignities)
    d9_dignities   = _g("d9_planet_dignities", _g("d9_dignities", {}))
    # D10 — now formal fields on NatalPayloadV2 (Steps 1-2 fix)
    d10_lagna      = _g("d10_lagna_sign", "not available")
    d10_h_lords    = _g("d10_house_lords", {}) or {}
    d10_h_occ      = _g("d10_house_occupancy", {}) or {}
    d10_planet_sign = _g("d10_planet_sign", {}) or {}      # {planet: sign} if available

    # Yogas — NatalPayloadV2 uses detected_yogas (List[str]); "yogas" dict is a legacy format.
    # detected_yogas is the authoritative source; fall back through yogas_present → yogas.
    yogas_raw     = (_g("detected_yogas", None) or _g("yogas_present", None)
                     or _g("yogas", None) or [])
    yoga_names    = list(yogas_raw.keys()) if isinstance(yogas_raw, dict) else list(yogas_raw or [])

    # Nakshatra — Step 3 fix: moon_nakshatra is now a formal string field on NatalPayloadV2.
    # nakshatra_data["Moon"] may still be a string or dict; handle both defensively.
    _nak_data     = _g("nakshatra_data", {}) or {}
    moon_nak_raw  = _nak_data.get("Moon") or ""
    if isinstance(moon_nak_raw, dict):
        moon_nak  = moon_nak_raw.get("nakshatra") or moon_nak_raw.get("name") or ""
        moon_pada = (moon_nak_raw.get("pada")
                     or _g("moon_nakshatra_pada", 0)   # formal field (int, 1-4)
                     or "not available")
    else:
        moon_nak  = (_g("moon_nakshatra", "") or str(moon_nak_raw)) or "not available"
        moon_pada = _g("moon_nakshatra_pada", "not available")  # formal field set by engine_io.py

    lagna_nak_raw = _nak_data.get("Lagna") or ""
    lagna_nak     = (lagna_nak_raw.get("nakshatra") if isinstance(lagna_nak_raw, dict)
                     else (str(lagna_nak_raw) if lagna_nak_raw else ""))
    if not lagna_nak:
        lagna_nak = _g("lagna_nakshatra", "not available")   # formal field set by engine_io.py

    # Planet nakshatras — now a formal field on NatalPayloadV2 (planet_nakshatras)
    planet_nakshatras = _g("planet_nakshatras", {}) or {}

    # Karakamsha — NatalPayloadV2 has karakamsha (the D9 sign of AK)
    karakamsha    = _g("karakamsha", _g("karakamsha_sign", "not available"))
    # Arudha / A10 — Step 4-5 fix: field is "arudha_lagna" (not "arudha_lagna_sign"),
    # and "a10_sign" is now stored by engine.py after compute_arudha_pada(10,...).
    cc_inner      = _g("career_context", {}) or {}
    arudha_lagna  = (_g("arudha_lagna", "")              # formal field set by engine.py
                     or cc_inner.get("arudha_lagna_sign")
                     or cc_inner.get("arudha_lagna")
                     or "not available")
    a10_sign      = (_g("a10_sign", "")                  # formal field set by engine.py
                     or cc_inner.get("a10_sign")
                     or cc_inner.get("karma_pada")
                     or "not available")

    # Career context
    cc            = cc_inner
    sector        = cc.get("industry_sector", _g("industry_sector", "not available"))
    designation   = cc.get("designation") or _g("designation", "not available")
    exp_years     = (cc.get("years_experience")          # key set by parse_career_context
                     or cc.get("experience_years")       # legacy alias
                     or _g("experience_years", "not available"))

    lines = [
        f"━━━ CHART SUMMARY: {name} ━━━",
        f"DOB: {dob}  |  Lagna: {lagna}  |  Current Age: {current_age}",
        f"Sector: {sector}  |  Designation: {designation}  |  Experience: {exp_years} yrs",
        "",
        "── KARAKAS ──────────────────────────────────────────",
        f"AK  (Atmakaraka):  {ak}  |  AmK (Amatyakaraka): {amk}",
        f"MK  (Matrikaraka): {mk}  |  BK  (Bhatrikaraka): {bk}",
        f"PK  (Putrakaraka): {pk}  |  GnK (Gnatikaraka):  {gnk}",
        f"DK  (Darakaraka):  {dk}",
        "",
        "── PLANET HOUSES (D1 Rasi) ─────────────────────────",
        _fmt_planet_house(planet_house if isinstance(planet_house, dict) else {}),
        "",
        "── HOUSE LORDS ─────────────────────────────────────",
        ", ".join(f"H{k}:{v}" for k, v in sorted((house_lords or {}).items())) or "not available",
        "",
        "── PLANET SIGNS ────────────────────────────────────",
        ", ".join(f"{p}:{s}" for p, s in sorted((planet_sign or {}).items())) or "not available",
        "",
        "── DIGNITIES (D1) ──────────────────────────────────",
        _fmt_dignities(dignities),
        "",
        f"── RETROGRADE PLANETS: {', '.join(retrogrades) if retrogrades else 'None'} ──",
        "",
        "── KP CUSP DATA ─────────────────────────────────────",
        f"H10: star={h10_kp.get('star_lord','?')} sub={h10_kp.get('sub_lord','?')} ssl={h10_kp.get('sub_sub_lord','?')}",
        f"H11: star={h11_kp.get('star_lord','?')} sub={h11_kp.get('sub_lord','?')} ssl={h11_kp.get('sub_sub_lord','?')}",
        f"H6:  star={h6_kp.get('star_lord','?')}  sub={h6_kp.get('sub_lord','?')}",
        f"H2:  star={h2_kp.get('star_lord','?')}  sub={h2_kp.get('sub_lord','?')}",
        "",
        "── D9 NAVAMSHA DIGNITIES ────────────────────────────",
        _fmt_dignities(d9_dignities),
        "",
        "── D10 DASHAMSHA (Career Chart) ─────────────────────",
        f"D10 Lagna: {d10_lagna}",
        f"D10 House Lords: {', '.join(f'H{k}:{v}' for k,v in sorted((d10_h_lords or {}).items())) or 'not available'}",
    ]
    # D10 house occupancy — which planets sit in which D10 house
    if d10_h_occ:
        _occ_parts = []
        for _h in sorted(d10_h_occ.keys(), key=lambda x: int(x) if str(x).isdigit() else 99):
            _planets = d10_h_occ[_h]
            if _planets:
                _occ_parts.append(f"H{_h}:[{','.join(_planets)}]")
        if _occ_parts:
            lines.append(f"D10 Planet Occupancy: {', '.join(_occ_parts)}")
    # D10 planet signs
    if d10_planet_sign:
        lines.append(
            f"D10 Planet Signs: "
            + ", ".join(f"{p}:{s}" for p, s in sorted(d10_planet_sign.items()))
        )
    lines += [
        "",
        "── NAKSHATRA / SPECIAL LAGNAS ───────────────────────",
        f"Moon Nakshatra: {moon_nak} Pada {moon_pada}  |  Lagna Nakshatra: {lagna_nak}",
        f"Karakamsha (D9 AK sign): {karakamsha}",
        f"Arudha Lagna (A1): {arudha_lagna}  |  Karma Pada (A10): {a10_sign}",
        (("Planet Nakshatras: "
          + ", ".join(f"{p}:{n}" for p, n in sorted(planet_nakshatras.items()) if n))
         if planet_nakshatras else "Planet Nakshatras: not available"),
        "",
        "── D10 DEVATA DIAGNOSTICS ───────────────────────────",
        "Four career-problem archetypes derived from Dasamsa (D10).",
        "Each archetype identifies the key planet (lord) and its devata.",
        "When this devata is unworshipped/weak, the archetype manifests strongly.",
    ] + _build_d10_devata_lines(_g("d10_devata_diagnostics", {})) + [
        "",
        "── ACTIVE YOGAS ─────────────────────────────────────",
        (", ".join(yoga_names[:20]) if yoga_names else "not available"),
        "",
        "── COMPLETE VIMSHOTTARI DASHA (MD → AD → PD with calendar dates) ───────────",
    ]

    if dasha_seq and isinstance(dasha_seq, list):
        for ds in dasha_seq:
            if not isinstance(ds, dict):
                continue
            md_planet = (ds.get("planet") or ds.get("md_planet")
                         or ds.get("lord") or "?")
            md_start  = (ds.get("start") or ds.get("start_date") or
                         (f"age {ds.get('start_age','?')}" if ds.get("start_age") else "?"))
            md_end    = (ds.get("end") or ds.get("end_date") or
                         (f"age {ds.get('end_age','?')}" if ds.get("end_age") else "?"))
            lines.append(f"  MD {md_planet}: {md_start} → {md_end}")

            ads = ds.get("antardashas") or ds.get("sub_periods") or []
            for ad in ads:
                if not isinstance(ad, dict):
                    continue
                ad_planet = ad.get("planet") or ad.get("ad_planet") or ad.get("lord") or "?"
                ad_start  = (ad.get("start") or ad.get("start_date") or
                             (f"age {ad.get('start_age','?')}" if ad.get("start_age") else "?"))
                ad_end    = (ad.get("end") or ad.get("end_date") or
                             (f"age {ad.get('end_age','?')}" if ad.get("end_age") else "?"))
                lines.append(f"    AD {ad_planet}: {ad_start} → {ad_end}")

                # Pratyantardashas (3rd level) — key for precise event timing
                pds = ad.get("pratyantardashas") or []
                for pd in pds:
                    if not isinstance(pd, dict):
                        continue
                    pd_planet = pd.get("planet") or pd.get("pd_lord") or "?"
